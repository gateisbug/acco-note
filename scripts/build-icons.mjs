import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const source=resolve('node_modules/lucide-static');
const destination=resolve('public/vendor/lucide');
const mapping={trash:'trash-2',ledger:'notebook-pen',budget:'wallet-cards',savings:'piggy-bank',manage:'sliders-horizontal',arrow:'chevron-right',arrowLeft:'chevron-left',arrowDown:'chevron-down',plus:'plus',search:'search',filter:'list-filter',calendar:'calendar-days',coffee:'coffee',food:'utensils',bag:'shopping-bag',transit:'train-front',home:'house',check:'check',close:'x',download:'download',repeat:'repeat-2',chart:'chart-no-axes-column'};
await mkdir(destination,{recursive:true});
const icons={};
for(const [name,file] of Object.entries(mapping)){
  const svg=await readFile(resolve(source,'icons',file+'.svg'),'utf8');
  icons[name]=svg.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)[1].trim().replace(/\s+/g,' ');
  if(['arrowDown','calendar'].includes(name))await writeFile(resolve(destination,file+'.svg'),svg.replace('stroke="currentColor"','stroke="#5a6d88"'));
}
const {version}=JSON.parse(await readFile(resolve(source,'package.json'),'utf8'));
await writeFile(resolve(destination,'icons.js'),`/* Lucide ${version}, ISC. Generated by npm run build:icons. */\nconst icons = ${JSON.stringify(icons,null,2)};\n`);
await copyFile(resolve(source,'LICENSE'),resolve(destination,'LICENSE'));
console.log(`Built ${Object.keys(icons).length} Lucide icons (${version}).`);
